"""Acceptance: separate ability damage / drain controls and timed ailment drain."""
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).parent
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=browser.new_page(viewport={'width':1560,'height':1000})
 errors=[];page.on('pageerror', lambda e: errors.append(str(e)))
 page.set_content((ROOT/'index.html').read_text())
 assert 'Tabletop Kernel' in page.locator('h1').inner_text()
 page.locator('#activate').click()
 page.locator('#register-creature').click()
 page.locator('#spawn-creature').click()
 page.locator('#gm-target').select_option('raider_1')
 page.locator('#gm-ability').select_option('str')
 page.locator('#gm-ability-op').select_option('apply_ability_damage')
 page.locator('#gm-ability-amount').fill('4')
 page.locator('#gm-ability-apply').click()
 assert 'Ability damage: STR 4' in page.locator('#stats').inner_text()
 assert 'Attack +5' in page.locator('#stats').inner_text()
 page.locator('#gm-ability-op').select_option('apply_ability_drain')
 page.locator('#gm-ability-amount').fill('1')
 page.locator('#gm-ability-apply').click()
 assert 'Ability drain: STR 1' in page.locator('#stats').inner_text()
 assert 'STR 16 → 15' in page.locator('#stats').inner_text()
 assert 'Attack +4' in page.locator('#stats').inner_text()
 page.locator('#gm-ability-op').select_option('heal_ability_damage')
 page.locator('#gm-ability-amount').fill('4')
 page.locator('#gm-ability-apply').click()
 assert 'Attack +6' in page.locator('#stats').inner_text()
 page.locator('#gm-ability-op').select_option('restore_ability_drain')
 page.locator('#gm-ability-amount').fill('1')
 page.locator('#gm-ability-apply').click()
 assert 'Attack +7' in page.locator('#stats').inner_text()
 assert 'Ability drain: STR 1' not in page.locator('#stats').inner_text()
 # A sample ailment with an ability_drain effect can be imported directly.
 page.locator('#ailment-json').fill('{"id":"new-drain","name":"Test Drain","kind":"disease","effects":[{"kind":"ability_drain","ability":"wis","dice":{"count":1,"sides":4}}]}')
 page.locator('#ailment-register').click()
 page.locator('#ailment-target').select_option('raider_1')
 page.evaluate('() => { instance.s.testRolls = [2]; }')
 page.locator('#ailment-expose').click()
 assert 'Ability drain: WIS 2' in page.locator('#stats').inner_text()
 assert not errors,errors
 print('Browser V3.7 PASS: damage, drain, healing/restoration, ailment ability drain, stat recalculation.')
 browser.close()
